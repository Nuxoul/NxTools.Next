import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { join, resolve } from 'node:path'
import { mkdir, writeFile } from 'node:fs/promises'
const tools = process.env.NXTOOLS_PREVIEW_TOOLS
const require = createRequire(tools ? join(resolve(tools), 'package.json') : import.meta.url)
const { chromium } = require('playwright-core')
const base = process.argv[2] || 'http://127.0.0.1:4782/docs/ui/theme-preview/preview.html'
const output = process.argv[3] || process.env.PI_SCRATCH_DIR
if (!output) throw new Error('Pass an output directory')
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true })
const page = await browser.newPage({ viewport: { width: 1100, height: 1000 }, reducedMotion: 'no-preference' })
const errors = []
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`) })
let checks = 0
const verify = (condition, message) => { assert.ok(condition, message); checks++ }
const button = name => page.getByRole('button', { name, exact: true })
const state = () => page.locator('#example').evaluate(node => ({ theme: node.dataset.previewTheme, palette: node.dataset.previewPalette, mode: node.dataset.previewMode }))
const settle = () => page.waitForTimeout(240)
const shot = name => page.screenshot({ path: join(output, `${name}.png`), fullPage: true })
try {
  await page.goto(base)
  await page.waitForFunction(() => [...document.fonts].some(font => font.family.replaceAll('"', '') === 'Sarasa UI SC' && font.status === 'loaded'))
  verify((await state()).theme === 'acrylic', 'Initial acrylic theme')
  await page.locator('.nx-workbench').evaluate(node => { node.dataset.retained = 'yes' })
  await page.getByRole('combobox', { name: '配色' }).selectOption('graphite')
  await button('现有主题').click()
  await settle()
  verify((await state()).palette === 'graphite', 'Theme preserves independently selected palette')
  verify(await page.locator('.nx-workbench').getAttribute('data-retained') === 'yes', 'Theme retains window DOM identity')
  verify(await page.locator('.nx-workbench').evaluate(node => getComputedStyle(node).backdropFilter) === 'none', 'Current theme is solid')
  await button('磨砂亚克力').click()
  await settle()
  verify((await state()).palette === 'graphite', 'Acrylic preserves palette')
  verify((await page.locator('.nx-workbench').evaluate(node => getComputedStyle(node).backdropFilter)).includes('blur'), 'Acrylic material applied')
  await button('切换到浅色').click()
  verify((await state()).mode === 'light' && (await state()).theme === 'acrylic', 'Light mode independent of theme')
  await shot('theme-light-overview')
  await button('切换到深色').click()
  await page.getByRole('combobox', { name: '配色' }).selectOption('frappe')
  for (const name of ['工具', '设置', 'Markdown', '菜单与浮层', '下载']) {
    await page.getByRole('navigation', { name: '总览表面' }).getByRole('button', { name, exact: true }).click()
    verify(await page.locator('.nx-main-pane').innerText() !== '', `Overview surface ${name}`)
  }
  await shot('theme-dark-overview')
  await button('快捷启动').click()
  const inputBox = () => page.locator('[data-target="search-input"]').boundingBox()
  const fixed = await inputBox()
  await button('播放演示').click()
  await page.waitForFunction(() => document.querySelector('.nx-search-results')?.getAttribute('data-visible') === 'false')
  await page.waitForFunction(() => document.querySelector('.nx-search-results')?.getAttribute('data-visible') === 'true')
  const after = await inputBox()
  verify(Math.abs(fixed.y - after.y) < .5 && Math.abs(fixed.height - after.height) < .5, 'Search input does not move with results')
  await page.waitForFunction(() => document.querySelector('.preview-play-status')?.textContent === '演示结束')
  verify(await page.locator('.nx-result').count() === 3, 'Three results at payoff')
  await shot('theme-search-payoff')
  await button('重播演示').click()
  await button('停止').click()
  verify(await page.locator('.nx-desktop').getAttribute('data-story-done') === 'true', 'Stop restores complete poster')
  await button('剪切板预览').click()
  await button('播放演示').click()
  await page.waitForFunction(() => document.querySelector('.nx-clip-preview')?.getAttribute('data-show') === 'false')
  await page.waitForFunction(() => document.querySelector('.nx-clip-preview')?.getAttribute('data-show') === 'true')
  await page.waitForFunction(() => document.querySelector('.preview-play-status')?.textContent === '演示结束')
  verify(await page.locator('.nx-clip-preview').getAttribute('data-show') === 'true', 'Clipboard ends with visible preview')
  await shot('theme-clipboard-payoff')
  await button('整套主题切换').click()
  await page.getByRole('combobox', { name: '配色' }).selectOption('graphite')
  verify(await page.locator('[data-target="apply-theme"]').evaluate(node => { const box = node.getBoundingClientRect(); const hit = document.elementFromPoint(box.x + box.width / 2, box.y + box.height / 2); return hit !== null && node.contains(hit) }), 'Apply action is not covered by another surface')
  await button('播放演示').click()
  await page.waitForFunction(() => document.querySelector('.nx-desktop')?.getAttribute('data-material') === 'current')
  await page.waitForFunction(() => document.querySelector('.nx-desktop')?.getAttribute('data-material') === 'acrylic')
  verify((await state()).palette === 'graphite', 'Apply story retains palette')
  verify(await page.locator('.nx-window').evaluateAll(nodes => nodes.every(node => getComputedStyle(node).backdropFilter.includes('blur'))), 'All visible story windows share material')
  await page.waitForFunction(() => document.querySelector('.preview-play-status')?.textContent === '演示结束')
  await shot('theme-switch-payoff')
  await button('重播演示').click()
  await page.getByRole('checkbox', { name: '减少动态效果' }).check()
  await settle()
  verify(await page.locator('.nx-desktop').getAttribute('data-story-done') === 'true', 'Reduced motion interrupts to poster')
  verify(await button('播放演示').isDisabled(), 'Reduced motion disables playback')
  verify(await page.evaluate(() => document.getAnimations().filter(animation => animation.playState === 'running').length) === 0, 'No CSS animations under reduced motion')
  await page.getByRole('checkbox', { name: '减少动态效果' }).uncheck()
  verify(await page.locator('.preview-play-status').innerText() === '点击播放，一次结束', 'Disabling reduction does not autoplay')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.waitForFunction(() => document.querySelector('.preview-reduced input')?.disabled === true)
  verify(await page.getByRole('checkbox', { name: /减少动态效果/ }).isDisabled(), 'System motion preference honored')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  for (const width of [763, 390, 358]) {
    await page.setViewportSize({ width, height: 1000 })
    for (const scene of ['快捷启动', '剪切板预览', '整套主题切换']) {
      await button(scene).click()
      await settle()
      verify(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}: host has no horizontal overflow`)
      const target = scene === '快捷启动' ? 'search-input' : scene === '剪切板预览' ? 'clip-record' : 'apply-theme'
      const bounds = await page.locator(`[data-target="${target}"]`).boundingBox()
      const stage = await page.locator('.ss-stage').boundingBox()
      verify(bounds.x >= stage.x - 1 && bounds.x + bounds.width <= stage.x + stage.width + 1 && bounds.y >= stage.y - 1 && bounds.y + bounds.height <= stage.y + stage.height + 1, `${width}: ${target} wholly inside frame`)
      if (width === 390) await shot(`theme-${target}-compact`)
    }
  }
  await page.setViewportSize({ width: 1100, height: 1000 })
  await button('主题总览').click()
  await button('现有主题').focus()
  await page.keyboard.press('Space')
  verify((await state()).theme === 'current', 'Keyboard activates theme choice')
  verify(await page.evaluate(() => document.activeElement?.matches(':focus-visible')), 'Keyboard focus visible')
  verify(errors.length === 0, `Browser errors: ${errors.join('; ')}`)
  const result = { status: 'passed', checks, browser: await browser.version(), errors }
  await writeFile(join(output, 'theme-interactions.json'), JSON.stringify(result, null, 2))
  console.log(JSON.stringify(result, null, 2))
} finally { await browser.close() }
