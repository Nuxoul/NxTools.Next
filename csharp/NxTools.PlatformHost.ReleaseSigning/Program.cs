using System.Globalization;
using System.Security.AccessControl;
using System.Security.Cryptography;
using System.Security.Principal;
using System.Text;
using NxTools.PlatformHost.Windows;

// Offline release tool only: no service, registry, pipe, enrollment or native product execution.
try
{
    switch (args.FirstOrDefault())
    {
        case "sign" when args.Length == 5:
            var manifest = TrustedReleaseManifest.SignPackage(args[1], args[2], long.Parse(args[3], CultureInfo.InvariantCulture), Guid.Parse(args[4]));
            Console.WriteLine($"Signed release {manifest.ReleaseId:D}, sequence {manifest.ReleaseSequence}, files {manifest.Files.Count}.");
            break;
        case "trust" when args.Length == 3:
            var spki = Convert.ToBase64String(TrustedReleaseManifest.PublicKeySpki(args[1]));
            var output = Path.GetFullPath(args[2]);
            if (StringComparer.OrdinalIgnoreCase.Equals(output, Path.GetFullPath(args[1]))) throw new InvalidOperationException("Trust output cannot replace the private key.");
            Directory.CreateDirectory(Path.GetDirectoryName(output)!);
            File.WriteAllText(output, "// Generated by scripts/write-update-trust.ps1. Public SPKI only; never private key material.\nnamespace NxTools.PlatformHost.Generated;\n\ninternal static class UpdateTrust\n{\n    internal const string PublicKeySpkiBase64 = \"" + spki + "\";\n}\n", new UTF8Encoding(false));
            Console.WriteLine("Wrote public release trust anchor.");
            break;
        case "new-key" when args.Length == 4:
            GenerateKey(args[1], args[2], int.Parse(args[3], CultureInfo.InvariantCulture));
            Console.WriteLine("Created owner-only release signing PEM. Keep it outside source and client packages.");
            break;
        default:
            Console.Error.WriteLine("Usage: sign PACKAGE EXISTING_PRIVATE_PEM SEQUENCE GUID | trust EXISTING_PRIVATE_PEM OUTPUT_CS | new-key NEW_PEM REPOSITORY_ROOT BITS");
            return 2;
    }
    return 0;
}
catch (Exception exception)
{
    // Do not print a PEM, source path or arbitrary exception message.
    Console.Error.WriteLine($"Release signing failed: {exception.GetType().Name}, HRESULT 0x{exception.HResult:X8}.");
    return 1;
}

static void GenerateKey(string requestedPath, string repositoryRoot, int bits)
{
    var path = Path.GetFullPath(requestedPath);
    var repository = Path.TrimEndingDirectorySeparator(Path.GetFullPath(repositoryRoot));
    if (path.Equals(repository, StringComparison.OrdinalIgnoreCase) || path.StartsWith(repository + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase) ||
        path.Split(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar).Any(part => part.Equals("artifacts", StringComparison.OrdinalIgnoreCase)))
        throw new InvalidOperationException("Private key must be outside repository and artifact directories.");
    if (bits is not (3072 or 4096)) throw new ArgumentOutOfRangeException(nameof(bits));
    // Existing directory only, no implicit key location or creation of a broad-access secret directory.
    using var locks = new TrustedReleaseManifest.PackageHandles(Path.GetDirectoryName(path)!);
    var owner = WindowsIdentity.GetCurrent().User ?? throw new InvalidOperationException("Missing owner identity.");
    var security = new FileSecurity();
    security.SetOwner(owner);
    security.SetAccessRuleProtection(true, false);
    security.AddAccessRule(new FileSystemAccessRule(owner, FileSystemRights.FullControl, AccessControlType.Allow));
    using var rsa = RSA.Create(bits);
    // ACL is applied at creation, before any private bytes are written. CreateNew never overwrites.
    using var stream = new FileInfo(path).Create(FileMode.CreateNew, FileSystemRights.FullControl, FileShare.None, 4096, FileOptions.None, security);
    var pem = Encoding.UTF8.GetBytes(rsa.ExportPkcs8PrivateKeyPem());
    try { stream.Write(pem); stream.Flush(true); }
    finally { CryptographicOperations.ZeroMemory(pem); }
}
