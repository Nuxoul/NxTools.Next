"""Generate bounded Finder pronunciation data from licensed, checked-in inputs.

Usage: python scripts/generate-pinyin-data.py [--check]
The pronunciation selection follows the reviewed WinShun behavior, but this
serializer is independently implemented. No network fetch or reference execution.
"""
import argparse
import hashlib
import pathlib
import re
import struct
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parents[1]
DATA = ROOT / "third_party/pinyin-data"
OUTPUT = ROOT / "rust/crates/nxtools-finder/src/pinyin_data"
FIRST, LAST = 0x4E00, 0x9FFF
HASHES = {
    "pinyin.txt": "621f8ca9eff8519f47e2b17b564fd318161e13bca07eea8c8e04993cd5d3b52e",
    "kTGHZ2013.txt": "83be5ecdfe0b8fcc1202ae45882a2f983c013db87ba68369d94a4dad775382bb",
}


def load(filename):
    raw = (DATA / filename).read_bytes()
    if hashlib.sha256(raw).hexdigest() != HASHES[filename]:
        raise SystemExit(f"unreviewed input: {filename}")
    readings = {}
    for line in raw.decode("utf-8").splitlines():
        match = re.match(r"U\+([0-9A-F]+):\s*([^#]+)", line)
        if not match or not FIRST <= int(match[1], 16) <= LAST:
            continue
        values = []
        for accented in match[2].strip().split(","):
            folded = []
            for character in unicodedata.normalize("NFD", accented.strip()):
                if character == "\u0308" and folded and folded[-1] == "u":
                    folded[-1] = "v"
                elif unicodedata.category(character) != "Mn":
                    folded.append(character)
            value = "".join(folded)
            if not re.fullmatch("[a-z]+", value):
                raise SystemExit(f"invalid syllable in {filename}")
            if value not in values:
                values.append(value)
        readings[int(match[1], 16)] = values
    return readings


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    common, standard = load("pinyin.txt"), load("kTGHZ2013.txt")
    selected = {}
    for code, values in common.items():
        allowed = standard.get(code)
        selected[code] = (values[:1] if allowed is None else
                          ([value for value in values if value in allowed] +
                           [value for value in allowed if value not in values])[:3])
    syllables = sorted({value for values in selected.values() for value in values})
    if len(syllables) >= 1024 or max(map(len, syllables)) > 6:
        raise SystemExit("reading bounds exceeded")
    numbers = {value: index + 1 for index, value in enumerate(syllables)}
    packed = bytearray()
    for code in range(FIRST, LAST + 1):
        value = sum(numbers[reading] << (10 * index)
                    for index, reading in enumerate(selected.get(code, [])))
        packed.extend(struct.pack("<I", value))
    source = ['// Generated by scripts/generate-pinyin-data.py; do not edit.',
              '// MIT pinyin-data (c) 2016 mozillazg; see third_party/pinyin-data/LICENSE.',
              '#[rustfmt::skip]',
              f'pub(super) const SYLLABLES: [&str; {len(syllables)}] = [']
    for offset in range(0, len(syllables), 10):
        source.append("    " + ", ".join(f'"{value}"' for value in syllables[offset:offset+10]) + ",")
    source.append("];\n")
    outputs = {"readings.bin": bytes(packed), "syllables.rs": "\n".join(source).encode()}
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for filename, content in outputs.items():
        path = OUTPUT / filename
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                raise SystemExit(f"stale generated data: {filename}")
        else:
            path.write_bytes(content)
    print(f"pinyin-data: {len(selected)} characters, {len(syllables)} syllables, "
          f"{len(packed)} packed bytes; {'verified' if args.check else 'generated'}")


if __name__ == "__main__":
    main()
